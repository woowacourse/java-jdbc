/**
 * 격리 레벨(Isolation Level)에 따라 여러 사용자가 동시에 db에 접근했을 때 어떤 문제가 발생하는지 확인해보자.
 * ❗phantom reads는 docker를 실행한 상태에서 테스트를 실행한다.
 * ❗이 테스트의 phantom reads 및 UPDATE 혼합 조회는 MySQL InnoDB로 확인한다.
 *
 * 참고 링크
 * https://en.wikipedia.org/wiki/Isolation_(database_systems)
 *
 * 각 테스트에서 어떤 현상이 발생하는지 직접 경험해보고 아래 표를 채워보자.
 * + : 발생
 * - : 발생하지 않음
 *   Read phenomena | Dirty reads | Non-repeatable reads | Phantom reads
 * Isolation level  |             |                      |
 * -----------------|-------------|----------------------|--------------
 * Read Uncommitted |      +      |          +           |
 * Read Committed   |      -      |          +           |
 * Repeatable Read  |      -      |          -           |
 * Serializable     |      -      |          -           |
 */
class Stage1Test {

    private static final Logger log = LoggerFactory.getLogger(Stage1Test.class);
    private DataSource dataSource;
    private UserDao userDao;

    private void setUp(final DataSource dataSource) {
        this.dataSource = dataSource;
        DatabasePopulatorUtils.execute(dataSource);
        this.userDao = new UserDao(dataSource);
    }

    /**
     * 격리 수준에 따라 어떤 현상이 발생하는지 테스트를 돌려 직접 눈으로 확인하고 표를 채워보자.
     * + : 발생
     * - : 발생하지 않음
     *   Read phenomena | Dirty reads
     * Isolation level  |
     * -----------------|-------------
     * Read Uncommitted | +
     * Read Committed   | -
     * Repeatable Read  | -
     * Serializable     | -
     */
    @ParameterizedTest(name = "{0}: dirty read = {2}")
    @CsvSource({
            "READ_UNCOMMITTED, 1, true",
            "READ_COMMITTED, 2, false",
            "REPEATABLE_READ, 4, false",
            "SERIALIZABLE, 8, false"
    })
    void dirtyReading(final String isolationName, final int isolationLevel,
                      final boolean dirtyReadExpected) throws SQLException {
        final var source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:dirty-reading-" + java.util.UUID.randomUUID());
        final var dao = new UserDao(source);

        // 별도 스레드 없이도 서로 다른 두 연결의 트랜잭션을 겹쳐 실행할 수 있다.
        try (final var writer = source.getConnection();
             final var reader = source.getConnection()) {
            try (final var statement = writer.createStatement()) {
                statement.execute("create table users (id bigint generated by default as identity primary key, "
                        + "account varchar(100), password varchar(100), email varchar(100))");
            }

            reader.setTransactionIsolation(isolationLevel);
            reader.setAutoCommit(false);
            writer.setAutoCommit(false);
            try {
                // A는 저장했지만 아직 커밋하지 않았다.
                dao.insert(writer, new User("gugu", "password", "hkkang@woowahan.com"));
                assertThat(dao.findByAccount(writer, "gugu")).isNotNull();

                // B가 A의 미커밋 데이터를 볼 수 있는지 확인한다.
                final var observed = dao.findByAccount(reader, "gugu");
                log.info("{}: rollback 전 B에게 보이는가? {}", isolationName, observed != null);
                if (dirtyReadExpected) {
                    assertThat(observed).isNotNull();
                    assertThat(observed.getAccount()).isEqualTo("gugu");
                } else {
                    assertThat(observed).isNull();
                }

                writer.rollback();
                reader.rollback(); // B의 기존 조회 트랜잭션도 끝내고 최종 상태를 확인한다.
                assertThat(dao.findByAccount(reader, "gugu")).isNull();
                log.info("{}: A rollback 후 새 조회 결과 없음", isolationName);
            } finally {
                reader.rollback();
                writer.rollback();
            }
        }
    }

    /**
     * 격리 수준에 따라 어떤 현상이 발생하는지 테스트를 돌려 직접 눈으로 확인하고 표를 채워보자.
     * + : 발생
     * - : 발생하지 않음
     *   Read phenomena | Non-repeatable reads
     * Isolation level  |
     * -----------------|---------------------
     * Read Uncommitted | +
     * Read Committed   | +
     * Repeatable Read  | -
     * Serializable     | -
     */
    @ParameterizedTest(name = "{0}: second password = {2}")
    @CsvSource({
            "READ_UNCOMMITTED, 1, qqqq",
            "READ_COMMITTED, 2, qqqq",
            "REPEATABLE_READ, 4, password",
            "SERIALIZABLE, 8, password"
    })
    void noneRepeatable(final String isolationName, final int isolationLevel,
                        final String expectedPassword) throws SQLException {
        final var source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:non-repeatable-" + java.util.UUID.randomUUID());
        final var dao = new UserDao(source);

        try (final var reader = source.getConnection();
             final var writer = source.getConnection()) {
            try (final var statement = writer.createStatement()) {
                statement.execute("create table users (id bigint generated by default as identity primary key, "
                        + "account varchar(100), password varchar(100), email varchar(100))");
            }
            // 초기 사용자는 자동 커밋으로 확정해 두 연결 모두 읽을 수 있게 한다.
            dao.insert(writer, new User("gugu", "password", "hkkang@woowahan.com"));

            reader.setTransactionIsolation(isolationLevel);
            reader.setAutoCommit(false);
            writer.setAutoCommit(false);
            try {
                // A의 첫 조회. A의 트랜잭션은 두 번째 조회까지 계속 유지한다.
                final var first = dao.findByAccount(reader, "gugu");
                assertThat(first.getPassword()).isEqualTo("password");

                // B는 같은 행을 변경한 뒤 명시적으로 커밋한다.
                final var changed = dao.findByAccount(writer, "gugu");
                changed.changePassword("qqqq");
                dao.update(writer, changed);
                writer.commit();

                final var second = dao.findByAccount(reader, "gugu");
                assertThat(second.getId()).isEqualTo(first.getId());
                assertThat(second.getPassword()).isEqualTo(expectedPassword);
                log.info("{}: A 첫 조회={}, B commit 후 A 재조회={}",
                        isolationName, first.getPassword(), second.getPassword());

                // A의 읽기 트랜잭션을 끝내도 B가 이미 커밋한 변경은 취소되지 않는다.
                reader.rollback();
                assertThat(dao.findByAccount(reader, "gugu").getPassword()).isEqualTo("qqqq");
                log.info("{}: A의 새 트랜잭션에서는 qqqq 조회", isolationName);
            } finally {
                reader.rollback();
                writer.rollback();
            }
        }
    }

    /**
     * MySQL InnoDB에서 일반 범위 조회와 UPDATE를 섞은 조회를 구분한다.
     * READ_COMMITTED: 일반 재조회 1 -> 2
     * REPEATABLE_READ: 일반 재조회 1 -> 1, 직접 UPDATE 후 재조회 1 -> 2
     */
    @ParameterizedTest(name = "{0}: update = {2}, second row count = {3}")
    @CsvSource({
            "READ_COMMITTED, 2, false, 2",
            "REPEATABLE_READ, 4, false, 1",
            "REPEATABLE_READ, 4, true, 2"
    })
    void phantomReading(final String isolationName, final int isolationLevel,
                        final boolean updateBeforeRead, final int expectedCount) throws SQLException {
        try (final var mysql = new MySQLContainer<>(DockerImageName.parse("mysql:8.0.30"))) {
            mysql.start();
            try (final var source = createMySQLDataSource(mysql);
                 final var reader = source.getConnection();
                 final var writer = source.getConnection()) {
                final var dao = new UserDao(source);
                try (final var statement = writer.createStatement()) {
                    statement.execute("create table users (id bigint auto_increment primary key, "
                            + "account varchar(100), password varchar(100), email varchar(100)) engine=InnoDB");
                }
                dao.insert(writer, new User("gugu", "password", "hkkang@woowahan.com"));

                reader.setTransactionIsolation(isolationLevel);
                reader.setAutoCommit(false);
                writer.setAutoCommit(false);
                try {
                    assertThat(dao.findGreaterThan(reader, 1)).hasSize(1);

                    // 별도 연결 B가 새 행을 넣고 커밋한다. A는 아직 같은 트랜잭션이다.
                    dao.insert(writer, new User("bird", "password", "bird@woowahan.com"));
                    writer.commit();

                    final var beforeUpdate = dao.findGreaterThan(reader, 1);
                    assertThat(beforeUpdate).hasSize(
                            isolationLevel == Connection.TRANSACTION_READ_COMMITTED ? 2 : 1);

                    // InnoDB의 UPDATE는 일반 SELECT의 과거 스냅샷에만 제한되지 않는다.
                    if (updateBeforeRead) {
                        dao.updatePasswordGreaterThan(reader, "qqqq", 1);
                    }
                    final var actual = dao.findGreaterThan(reader, 1);
                    assertThat(actual).hasSize(expectedCount);
                    if (updateBeforeRead) {
                        assertThat(actual).extracting(User::getPassword).containsOnly("qqqq");
                    }
                    log.info("{}: first=1, B commit 후={}, UPDATE={}, final={}",
                            isolationName, beforeUpdate.size(), updateBeforeRead, actual.size());

                    // A의 변경만 취소된다. B가 커밋한 bird는 남는다.
                    reader.rollback();
                    final var afterRollback = dao.findGreaterThan(reader, 1);
                    assertThat(afterRollback).extracting(User::getAccount)
                            .containsExactlyInAnyOrder("gugu", "bird");
                    assertThat(afterRollback).extracting(User::getPassword).containsOnly("password");
                } finally {
                    reader.rollback();
                    writer.rollback();
                }
            }
        }
    }

    private static HikariDataSource createMySQLDataSource(final JdbcDatabaseContainer<?> container) {
        final var config = new HikariConfig();
        config.setJdbcUrl(container.getJdbcUrl());
        config.setUsername(container.getUsername());
        config.setPassword(container.getPassword());
        config.setDriverClassName(container.getDriverClassName());
        return new HikariDataSource(config);
    }

    private static DataSource createH2DataSource() {
        final var jdbcDataSource = new JdbcDataSource();
        // h2 로그를 확인하고 싶을 때 사용
//        jdbcDataSource.setUrl("jdbc:h2:mem:test;DB_CLOSE_DELAY=-1;TRACE_LEVEL_SYSTEM_OUT=3;MODE=MYSQL");
        jdbcDataSource.setUrl("jdbc:h2:mem:test;DB_CLOSE_DELAY=-1;MODE=MYSQL;");
        jdbcDataSource.setUser("sa");
        jdbcDataSource.setPassword("");
        return jdbcDataSource;
    }

    private void sleep(double seconds) {
        try {
            TimeUnit.MILLISECONDS.sleep((long) (seconds * 1000));
        } catch (InterruptedException ignored) {
        }
    }
}
